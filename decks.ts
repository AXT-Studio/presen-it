/**
 * Metadata of every deck selected by the `presenit()` Vite plugin.
 *
 * The plugin replaces this module with the same generated module as
 * `virtual:presenit/decks`, so importing it outside a Vite app that uses the
 * plugin throws.
 *
 * ```ts
 * import { decks } from "@ayaexptech/presen-it/decks";
 * for (const deck of decks) console.log(deck.title, deck.url, deck.slideCount);
 * ```
 *
 * @module
 */
import type { PresenitDeck } from "./src/vite/decks.ts";

export type { PresenitDeck };

function unavailable(): never {
    throw new Error(
        "[presenit] @ayaexptech/presen-it/decks is generated by the presenit() Vite plugin. " +
            "Import it from code built by Vite with presenit() in plugins.",
    );
}

/** Every deck, ordered by Markdown path. */
export const decks: readonly PresenitDeck[] = unavailable();
